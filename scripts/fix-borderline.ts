async function main() {
  let okCount = 0;
  let skipCount = 0;
  for (const u of updates) {
    const existing = await db.query.questions.findFirst({
      where: eq(questions.id, u.id),
    });
    if (!existing) {
      console.log(`[SKIP] ${u.id} (${u.description}) — question not found`);
      skipCount++;
      continue;
    }

    const setObj: Record<string, unknown> = { updatedAt: new Date() };
    if (u.questionMd !== undefined) setObj.questionMd = u.questionMd;
    if (u.optionsJson !== undefined) setObj.optionsJson = u.optionsJson;
    if (u.correctAnswerJson !== undefined)
      setObj.correctAnswerJson = u.correctAnswerJson;
    if (u.explanationMd !== undefined) setObj.explanationMd = u.explanationMd;
    if (u.referencesJson !== undefined) setObj.referencesJson = u.referencesJson;
    if (u.source !== undefined) setObj.source = u.source;

    await db.update(questions).set(setObj).where(eq(questions.id, u.id));
    console.log(`[OK]  ${u.id} — ${u.description}`);
    okCount++;
  }

  console.log(
    `\nupdated=${okCount}, skipped=${skipCount}, total=${updates.length}`,
  );
  sqlite.close();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
